#!/usr/bin/env python3
"""Abide art library builder.

Every artwork collection lives in its own folder:  assets/art/<collection-id>/
  collection.json            id, title, size rules per category, offline size, and per-item alt text/tags
  masters/<category>/<name>.png   transparent PNG masters (never edited by this script)
  <category>/<name>-<width>.webp  web sizes (generated)

To add a new collection: create the folder, drop the masters in masters/<category>/,
write collection.json, then run:   python3 tools/build_art.py
It (re)builds missing or outdated WebP sizes and rewrites assets/art/registry.js,
which the app reads through abArt('<collection>:<category>/<name>') / abArt('<category>/<name>').
The worker saves each collection's "offline" size automatically.
"""
import json, os, glob
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
ART = os.path.join(ROOT, 'assets', 'art')

def build():
    reg = {'v': 1, 'collections': {}, 'items': {}, 'offline': []}
    for cj in sorted(glob.glob(os.path.join(ART, '*', 'collection.json'))):
        cdir = os.path.dirname(cj); col = json.load(open(cj, encoding='utf-8')); cid = col['id']
        reg['collections'][cid] = {'title': col.get('title'), 'path': 'assets/art/' + cid + '/'}
        for png in sorted(glob.glob(os.path.join(cdir, 'masters', '*', '*.png'))):
            cat = os.path.basename(os.path.dirname(png))
            if cat in ('source', 'alternates'): continue
            name = os.path.basename(png)[:-4]; key = cat + '/' + name
            meta = col.get('items', {}).get(key, {})
            im = Image.open(png); w, h = im.size
            rule = col.get('sizes', {}).get(cat, [320, 640])
            ws = [x for x in rule if x <= w] or [w]
            os.makedirs(os.path.join(cdir, cat), exist_ok=True)
            for x in ws:
                out = os.path.join(cdir, cat, '%s-%d.webp' % (name, x))
                if not os.path.exists(out) or os.path.getmtime(out) < os.path.getmtime(png):
                    im.convert('RGBA').resize((x, round(h * x / w)), Image.LANCZOS).save(out, 'WEBP', quality=84, method=6)
            item = {'c': cid, 'w': w, 'h': h, 's': ws, 'alt': meta.get('alt'), 'tags': meta.get('tags', [])}
            reg['items'][cid + ':' + key] = item
            reg['items'].setdefault(key, item)          # short name: first collection wins
            off = col.get('offline', {}).get(cat)
            if off:
                pick = min([x for x in ws if x >= off] or [ws[-1]])
                reg['offline'].append('assets/art/%s/%s/%s-%d.webp' % (cid, cat, name, pick))
    js = ('/* Abide art registry: generated by tools/build_art.py. Do not edit by hand. */\n'
          'window.ABIDE_ART=' + json.dumps(reg, ensure_ascii=False, separators=(',', ':')) + ';\n')
    open(os.path.join(ART, 'registry.js'), 'w', encoding='utf-8').write(js)
    print('collections:', len(reg['collections']), ' items:', len([k for k in reg['items'] if ':' in k]), ' offline files:', len(reg['offline']))

if __name__ == '__main__':
    build()
